def _normalized_key(value: Any) -> str:
    return re.sub(r"[^a-z0-9]+", "", str(value or "").lower())


def _is_missing_scalar(value: Any) -> bool:
    if value is None:
        return True
    if isinstance(value, str):
        return value.strip().lower() in MISSING_MARKERS
    return False


def _contains_forbidden_key(key: Any) -> bool:
    normalized = _normalized_key(key)
    if normalized in FORBIDDEN_PHI_KEYS:
        return True
    return any(part in normalized for part in FORBIDDEN_KEY_PARTS)


def _contains_forbidden_text(value: str) -> bool:
    lowered = value.lower()
    return any(term in lowered for term in FORBIDDEN_PRESENTATION_TERMS)


def _clean_string(value: str) -> str | None:
    text = re.sub(r"\s+", " ", value).strip()
    if not text or text.lower() in MISSING_MARKERS:
        return None
    if _contains_forbidden_text(text):
        return None
    return text


def _clean_value(value: Any, *, drop_phi: bool = True) -> Any:
    if _is_missing_scalar(value):
        return None

    if isinstance(value, bool):
        return value

    if isinstance(value, (int, float)):
        return value

    if isinstance(value, str):
        return _clean_string(value)

    if isinstance(value, list):
        output: list[Any] = []
        seen: set[str] = set()
        for item in value:
            cleaned = _clean_value(item, drop_phi=drop_phi)
            if cleaned in (None, "", [], {}):
                continue
            marker = json.dumps(cleaned, sort_keys=True, ensure_ascii=False)
            if marker in seen:
                continue
            seen.add(marker)
            output.append(cleaned)
        return output or None

    if isinstance(value, dict):
        # A structured clinical result whose actual value is missing must be
        # omitted completely; retaining only its unit/reference would make the
        # missing analyte salient to the model.
        if "value" in value and _is_missing_scalar(value.get("value")):
            return None

        output: dict[str, Any] = {}
        for key, item in value.items():
            if _contains_forbidden_key(key):
                continue
            if drop_phi and _normalized_key(key) in FORBIDDEN_PHI_KEYS:
                continue
            cleaned = _clean_value(item, drop_phi=drop_phi)
            if cleaned in (None, "", [], {}):
                continue
            output[str(key)] = cleaned
        return output or None

    return _clean_string(str(value))


def _merge_unique(*values: Any) -> list[str]:
    output: list[str] = []
    seen: set[str] = set()
    for value in values:
        items: Iterable[Any]
        if isinstance(value, list):
            items = value
        elif value in (None, "", {}):
            items = []
        else:
            items = [value]
        for item in items:
            cleaned = _clean_value(item)
            if isinstance(cleaned, dict):
                text = "; ".join(
                    f"{key}: {subvalue}"
                    for key, subvalue in cleaned.items()
                )
            else:
                text = str(cleaned or "").strip()
            if not text:
                continue
            marker = text.lower()
            if marker in seen:
                continue
            seen.add(marker)
            output.append(text)
    return output


def _first_dict(*values: Any) -> dict[str, Any]:
    for value in values:
        if isinstance(value, dict) and value:
            cleaned = _clean_value(value)
            if isinstance(cleaned, dict) and cleaned:
                return cleaned
    return {}


def _lab_bucket(key: str) -> str:
    normalized = _normalized_key(key)
    if normalized in {_normalized_key(item) for item in ELECTROLYTE_KEYS}:
        return "electrolytes"
    if normalized in {_normalized_key(item) for item in RENAL_KEYS}:
        return "renal"
    if normalized in {_normalized_key(item) for item in ISCHEMIA_KEYS} or normalized.startswith("troponin"):
        return "ischemia"
    if normalized in {_normalized_key(item) for item in INFECTION_KEYS}:
        return "infection"
    if normalized in {_normalized_key(item) for item in TOXICITY_KEYS} or "digoxin" in normalized:
        return "toxicity"
    if normalized in {_normalized_key(item) for item in METABOLIC_KEYS}:
        return "metabolic"
    return "labs"


def _categorize_labs(labs: dict[str, Any]) -> dict[str, dict[str, Any]]:
    output: dict[str, dict[str, Any]] = {
        "labs": {},
        "electrolytes": {},
        "renal": {},
        "ischemia": {},
        "infection": {},
        "toxicity": {},
        "metabolic": {},
    }
    for key, value in labs.items():
        cleaned = _clean_value(value)
        if cleaned in (None, "", [], {}):
            continue
        output[_lab_bucket(key)][str(key)] = cleaned
    return {key: value for key, value in output.items() if value}


def _pick(mapping: dict[str, Any], *keys: str) -> Any:
    for key in keys:
        if key in mapping and mapping[key] not in (None, "", [], {}):
            return mapping[key]
    return None


def _episode_section(envelope: dict[str, Any], pack: dict[str, Any]) -> dict[str, Any]:
    controlled = envelope.get("controlledRhythm") or {}
    diagnosis = controlled.get("diagnosis") or {}
    episode = pack.get("episode") or {}
    clinical = pack.get("clinicalContext") or {}
    measurements = (
        pack.get("ecgMeasurements")
        or (pack.get("ecg") or {}).get("measurements")
        or {}
    )

    label = (
        diagnosis.get("display")
        or episode.get("display")
        or measurements.get("rhythm")
        or episode.get("type")
    )

    symptoms_and_events = _merge_unique(
        episode.get("symptoms"),
        episode.get("recentEvents"),
        clinical.get("symptoms"),
        clinical.get("recentEvents"),
        clinical.get("preEventObservations"),
    )

    allowed_measurement_keys = (
        "ventricularRateBpm",
        "atrialRateBpm",
        "heartRateBpm",
        "regularity",
        "qrsDurationMs",
        "qtcMs",
        "qtMs",
        "prMs",
        "prIntervalMs",
        "axisDeg",
        "axisDegrees",
        "pWavePresent",
        "atrialActivityPresent",
        "atrioventricularAssociation",
        "stDeviationMm",
        "morphology",
        "ectopyPer10s",
        "preEventNote",
        "findings",
    )
    ecg = {
        key: _clean_value(measurements.get(key))
        for key in allowed_measurement_keys
        if _clean_value(measurements.get(key)) not in (None, "", [], {})
    }

    vitals = pack.get("vitals") or {}
    blood_pressure = vitals.get("bloodPressure") or vitals.get("bp") or {}
    hemodynamics = _first_dict(pack.get("hemodynamics"))
    if isinstance(blood_pressure, dict):
        cleaned_bp = _clean_value(blood_pressure)
        if cleaned_bp:
            hemodynamics.setdefault("bloodPressure", cleaned_bp)
    for key in (
        "pulsePresent",
        "conscious",
        "state",
        "hemodynamicState",
        "arterialLine",
        "note",
    ):
        value = _pick(hemodynamics, key)
        if value not in (None, "", [], {}):
            hemodynamics[key] = value

    output = {
        "label": _clean_value(label),
        "severity": _clean_value(episode.get("severity")),
        "durationSeconds": _clean_value(episode.get("durationSeconds")),
        "symptomsAndRecentEvents": symptoms_and_events or None,
        "ecgAndMorphology": ecg or None,
        "hemodynamics": hemodynamics or None,
    }
    return _clean_value(output, drop_phi=False) or {}


def _patient_section(pack: dict[str, Any]) -> dict[str, Any]:
    patient = pack.get("patient") or {}
    current_medications = _merge_unique(
        pack.get("medications"),
        patient.get("currentMedications"),
        pack.get("infusions"),
        patient.get("infusions"),
    )
    output = {
        "age": _clean_value(patient.get("age")),
        "sex": _clean_value(patient.get("sex") or patient.get("gender")),
        "relevantHistory": _clean_value(
            patient.get("history")
            or patient.get("relevantHistory")
            or patient.get("conditions")
        ),
        "relevantHomeMedications": _clean_value(patient.get("homeMedications")),
        "relevantCurrentMedications": current_medications or None,
    }
    return _clean_value(output, drop_phi=True) or {}


def _clinical_evidence_section(pack: dict[str, Any]) -> dict[str, Any]:
    labs = _clean_value(pack.get("labs") or {}) or {}
    categorized = _categorize_labs(labs if isinstance(labs, dict) else {})

    contextual = {
        "electrolytes": _first_dict(pack.get("electrolytes")),
        "ischemia": _first_dict(pack.get("ischemia")),
        "infection": _first_dict(pack.get("infection")),
        "renal": _first_dict(pack.get("renal")),
        "toxicity": _first_dict(pack.get("toxicity")),
        "qtContext": _first_dict(pack.get("qt")),
    }

    output: dict[str, Any] = {
        "vitals": _clean_value(pack.get("vitals") or {}),
        **categorized,
    }

    for section, value in contextual.items():
        if not value:
            continue
        existing = output.get(section)
        if isinstance(existing, dict):
            merged = dict(existing)
            for key, item in value.items():
                if key not in merged:
                    merged[key] = item
            output[section] = merged
        else:
            output[section] = value

    return _clean_value(output, drop_phi=False) or {}


def _confidence_is_usable(value: Any) -> bool:
    text = str(value or "").strip().lower()
    return text in {"moderate", "high", "good", "ready"}


def _phase6_measurement(
    section: dict[str, Any],
    *,
    value_keys: tuple[str, ...],
    valid_keys: tuple[str, ...],
    confidence_keys: tuple[str, ...],
    unit: str,
) -> dict[str, Any] | None:
    value = _pick(section, *value_keys)
    if value is None:
        return None
    validity = _pick(section, *valid_keys)
    if validity is False:
        return None
    confidence = _pick(section, *confidence_keys)
    if confidence is not None and not _confidence_is_usable(confidence):
        return None
    output: dict[str, Any] = {"value": value, "unit": unit}
    if confidence:
        output["confidence"] = str(confidence).lower()
    return output


def _phase6_section(envelope: dict[str, Any]) -> dict[str, Any]:
    phase6 = (
        envelope.get("phase6WindowedAnalysis")
        or envelope.get("analysisWindowed")
        or envelope.get("deterministicAnalysis")
        or {}
    )
    if isinstance(phase6.get("windowedAnalysis"), dict):
        phase6 = phase6["windowedAnalysis"]

    controlled: dict[str, Any] = {}
    pre: dict[str, Any] = {}
    post: dict[str, Any] = {}

    heart_rate = phase6.get("heartRate") or phase6.get("rhythm") or {}
    qrs = phase6.get("qrs") or {}

    event_hr = _phase6_measurement(
        heart_rate,
        value_keys=("eventMedianBpm", "controlledEventMedianBpm"),
        valid_keys=("eventMeasurementValid", "controlledEventMeasurementValid"),
        confidence_keys=("eventConfidenceGrade", "controlledEventConfidenceGrade"),
        unit="bpm",
    )
    if event_hr:
        controlled["medianHeartRate"] = event_hr

    event_qrs = _phase6_measurement(
        qrs,
        value_keys=("eventMedianMs", "controlledEventMedianMs"),
        valid_keys=("eventMeasurementValid", "controlledEventMeasurementValid"),
        confidence_keys=("eventConfidenceGrade", "controlledEventConfidenceGrade"),
        unit="ms",
    )
    if event_qrs:
        controlled["medianQrsDuration"] = event_qrs

    for target, key, label, unit in (
        (pre, "preEventMedianBpm", "medianHeartRate", "bpm"),
        (post, "postEventMedianBpm", "medianHeartRate", "bpm"),
    ):
        value = heart_rate.get(key)
        if value is not None:
            target[label] = {"value": value, "unit": unit}

    for target, key, label, unit in (
        (pre, "preEventMedianMs", "medianQrsDuration", "ms"),
        (post, "postEventMedianMs", "medianQrsDuration", "ms"),
    ):
        value = qrs.get(key)
        if value is not None:
            target[label] = {"value": value, "unit": unit}

    comparisons: dict[str, Any] = {}
    morphology = phase6.get("morphology") or {}
    morphology_score = _pick(
        morphology,
        "eventVsPreDifferenceScore",
        "controlledEventVsPreDifferenceScore",
    )
    if isinstance(morphology_score, (int, float)):
        label = (
            "marked morphology change"
            if morphology_score >= 0.6
            else "moderate morphology change"
            if morphology_score >= 0.3
            else "limited morphology change"
        )
        comparisons["eventVsPreMorphology"] = {
            "interpretation": label,
            "differenceScore": morphology_score,
        }

    for item in envelope.get("measurementConflicts") or []:
        if not isinstance(item, dict):
            continue
        same_window = item.get("sameWindow")
        valid = item.get("measurementValid")
        confidence = item.get("confidenceGrade")
        etiologically_material = any(
            item.get(key) is True
            for key in (
                "etiologyMaterial",
                "materialToEtiology",
                "clinicallyMaterialToEtiology",
                "presentationMaterial",
            )
        )
        if same_window is False or valid is False or not etiologically_material:
            continue
        if confidence is not None and not _confidence_is_usable(confidence):
            continue
        metric = str(item.get("metric") or item.get("id") or "measurement")
        comparisons[metric] = _clean_value(
            {
                "episodePackValue": item.get("controlledEventValue", item.get("controlledValue")),
                "phase6Value": item.get("phase6EventValue", item.get("independentValue")),
                "unit": item.get("unit"),
                "difference": item.get("difference"),
            },
            drop_phi=False,
        )

    output = {
        "controlledEventMeasurements": controlled or None,
        "preEventMeasurements": pre or None,
        "postEventMeasurements": post or None,
        "clinicallyRelevantComparisons": comparisons or None,
    }
    return _clean_value(output, drop_phi=False) or {}


def build_model_clinical_evidence(
    episode_pack: dict[str, Any] | None = None,
    phase6_analysis: dict[str, Any] | None = None,
    *,
    evidence_bundle: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Return a compact clinical-only object for the model.

    The preferred runtime input is ``evidence_bundle``. ``episode_pack`` and
    ``phase6_analysis`` are accepted for focused tests and offline use.
    """
    envelope = deepcopy(evidence_bundle or {})
    if episode_pack is not None:
        envelope.setdefault("episodePackContext", deepcopy(episode_pack))
    if phase6_analysis is not None:
        envelope.setdefault("phase6WindowedAnalysis", deepcopy(phase6_analysis))

    pack = envelope.get("episodePackContext") or episode_pack or {}
    if not isinstance(pack, dict):
        pack = {}

    output = {
        "episode": _episode_section(envelope, pack),
        "patientContext": _patient_section(pack),
        "clinicalEvidence": _clinical_evidence_section(pack),
        "phase6": _phase6_section(envelope),
    }
    cleaned = _clean_value(output, drop_phi=False) or {}

    serialized = json.dumps(cleaned, ensure_ascii=False).lower()
    forbidden = [term for term in FORBIDDEN_PRESENTATION_TERMS if term in serialized]
    if forbidden:
        raise ValueError(
            "Compact model clinical evidence contains forbidden infrastructure/provenance text: "
            + ", ".join(sorted(set(forbidden)))
        )
    return cleaned


def validate_model_output_v603(payload: dict[str, Any]) -> None:
    required_strings = (
        "episodeSummary",
        "mostLikelyEtiologyAndClinicalContext",
    )
    invalid: list[str] = []
    for field in required_strings:
        if not isinstance(payload.get(field), str) or not payload[field].strip():
            invalid.append(field)
    factors = payload.get("contributingFactors")
    uncertainty = payload.get("materialEtiologicUncertainty")
    if not isinstance(factors, list) or not 1 <= len(factors) <= 5:
        invalid.append("contributingFactors")
    elif not all(isinstance(item, str) and item.strip() for item in factors):
        invalid.append("contributingFactors")
    if not isinstance(uncertainty, list) or len(uncertainty) > 2:
        invalid.append("materialEtiologicUncertainty")
    elif not all(isinstance(item, str) and item.strip() for item in uncertainty):
        invalid.append("materialEtiologicUncertainty")
    expected = {
        "episodeSummary",
        "mostLikelyEtiologyAndClinicalContext",
        "contributingFactors",
        "materialEtiologicUncertainty",
    }
    unexpected = sorted(set(payload) - expected)
    if invalid or unexpected:
        raise ValueError(
            "The model response did not match the four-field V6.0.3 contract. "
            f"invalid={sorted(set(invalid))}; unexpected={unexpected}"
        )


def _clean_presentation_text(value: Any) -> str:
    text = str(value or "").strip()
    if not text:
        return ""
    parts = re.split(r"(?<=[.!?])\s+", text)
    kept: list[str] = []
    for part in parts:
        sentence = part.strip()
        if not sentence:
            continue
        if _contains_forbidden_text(sentence):
            continue
        if GENERIC_MISSING_PATTERN.search(sentence):
            continue
        kept.append(sentence)
    return " ".join(kept).strip()


def sanitize_presentation_items(values: Any) -> list[str]:
    output: list[str] = []
    seen: set[str] = set()
    for value in values if isinstance(values, list) else []:
        cleaned = _clean_presentation_text(value)
        if not cleaned:
            continue
        marker = cleaned.lower()
        if marker in seen:
            continue
        seen.add(marker)
        output.append(cleaned)
    return output


def adapt_model_output_v603_to_legacy(payload: dict[str, Any]) -> dict[str, Any]:
    validate_model_output_v603(payload)
    episode_summary = _clean_presentation_text(payload["episodeSummary"])
    combined = _clean_presentation_text(payload["mostLikelyEtiologyAndClinicalContext"])
    factors = sanitize_presentation_items(payload.get("contributingFactors"))[:5]
    uncertainty = sanitize_presentation_items(payload.get("materialEtiologicUncertainty"))[:2]
    if not episode_summary or not combined or not factors:
        raise ValueError("The sanitized V6.0.3 model output is missing required clinical content.")
    return {
        "episodeSummary": episode_summary,
        "detectedEpisodeContext": episode_summary,
        "mostLikelyEtiology": combined,
        "contributingFactors": factors,
        "uncertaintyAndMissingData": uncertainty,
    }


def sanitize_legacy_model_output(payload: dict[str, Any]) -> dict[str, Any]:
    episode_summary = _clean_presentation_text(payload.get("episodeSummary"))
    detected = _clean_presentation_text(
        payload.get("detectedEpisodeContext")
        or payload.get("clinicalContext")
        or episode_summary
    )
    etiology = _clean_presentation_text(
        payload.get("mostLikelyEtiologyAndClinicalContext")
        or payload.get("mostLikelyEtiology")
        or payload.get("clinicalContext")
    )
    factors = sanitize_presentation_items(payload.get("contributingFactors"))[:5]
    uncertainty = sanitize_presentation_items(
        payload.get("materialEtiologicUncertainty")
        or payload.get("uncertaintyAndMissingData")
    )[:2]
    return {
        "episodeSummary": episode_summary,
        "detectedEpisodeContext": detected or episode_summary,
        "mostLikelyEtiology": etiology,
        "contributingFactors": factors,
        "uncertaintyAndMissingData": uncertainty,
    }


def presentation_narrative_from_legacy(payload: dict[str, Any]) -> dict[str, Any]:
    cleaned = sanitize_legacy_model_output(payload)
    return {
        "episodeSummary": cleaned["episodeSummary"],
        "mostLikelyEtiologyAndClinicalContext": cleaned["mostLikelyEtiology"],
        "contributingFactors": cleaned["contributingFactors"],
        "materialEtiologicUncertainty": cleaned["uncertaintyAndMissingData"],
    }


# Backward-compatible names retained so existing V6.0.2 imports do not break.
