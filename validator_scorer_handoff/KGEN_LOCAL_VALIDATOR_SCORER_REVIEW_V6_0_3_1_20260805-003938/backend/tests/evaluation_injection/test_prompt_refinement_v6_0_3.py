from __future__ import annotations

from app.evaluation_injection.grounded_prompt_builder import EPISODE_PACK_SYSTEM_PROMPT


def test_refined_prompt_contains_required_clinical_rules() -> None:
    for phrase in (
        "causal, precipitating, or predisposing",
        "AVNRT from AVRT",
        "Do not use materialEtiologicUncertainty to list routine unavailable",
        "Return valid JSON only",
    ):
        assert phrase in EPISODE_PACK_SYSTEM_PROMPT


def test_refined_prompt_does_not_leak_infrastructure() -> None:
    lowered = EPISODE_PACK_SYSTEM_PROMPT.lower()
    for term in ("incart", "api range", "oracle", "fhir", "generated by the slm", "not an independent diagnosis"):
        assert term not in lowered
